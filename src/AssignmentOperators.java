public class AssignmentOperators {
    public static void main(String[] args){
        int a = 10;
        int b = 20;
        int c = 30;
        int d = 45;
        int e = 50;

        a += 5;
        b -= 5;
        c *= 5;
        d /= 5;
        e %= 5;

        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(e);


    }
}
